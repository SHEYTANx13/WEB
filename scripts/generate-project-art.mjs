/* 5 — This website: the static living system                           */
/* A star identity core linking six world scenes and a chained blog.    */
/* ------------------------------------------------------------------ */

function webArtwork() {
  const parts = [dotGrid()];
  const cx = 330;
  const cy = 315;

  /* The identity core */
  parts.push(brandStar(cx, cy, 52, C.red));
  parts.push(
    `<circle cx="${cx}" cy="${cy}" r="92" fill="none" stroke="${C.line}" stroke-width="1" stroke-dasharray="3 6"/>`
  );

  /* Six scene nodes in an arc to the right */
  const sceneX = 880;
  const sceneYs = [90, 172, 254, 336, 418, 500];
  for (const y of sceneYs) {
    parts.push(link(cx, cy, sceneX, y, { opacity: 0.8 }));
  }
  for (const y of sceneYs) {
    parts.push(node(sceneX, y, { r: 7, fill: C.ink }));
  }

  /* The blog chain below the arc */
  const chainX = 560;
  const chainY = 545;
  parts.push(link(cx, cy, chainX, chainY, { opacity: 0.8 }));
  parts.push(frame(chainX - 26, chainY - 17, 52, 34, { stroke: C.inkDim, width: 1.4, rx: 7 }));
  parts.push(frame(chainX + 62, chainY - 17, 52, 34, { stroke: C.inkDim, width: 1.4, rx: 7 }));
  parts.push(frame(chainX + 150, chainY - 17, 52, 34, { stroke: C.red, width: 1.4, rx: 7 }));
  parts.push(
    `<path d="M${chainX + 27},${chainY} L${chainX + 61},${chainY} M${chainX + 115},${chainY} L${chainX + 149},${chainY}" stroke="${C.inkDim}" stroke-width="1.4"/>`
  );

  return wrap(
    "This website as a static living system — a red 13-point identity core linking six world scenes and a chained blog route tree",
    parts.join("\n  ")
  );
}

/* ------------------------------------------------------------------ */
/* Main                                                                 */
/* ------------------------------------------------------------------ */

const ARTWORKS = [
  { file: "sheytan-agent-lab.svg", render: sheytanArtwork },
  { file: "uhit-intelligence-scale.svg", render: uhitArtwork },
  { file: "freeiran-vpn-mesh.svg", render: freeiranArtwork },
  { file: "red-magic-organism.svg", render: redMagicArtwork },
  { file: "web-static-living-system.svg", render: webArtwork }
];

async function main() {
  await mkdir(CANONICAL_DIR, { recursive: true });
  await mkdir(RUNTIME_DIR, { recursive: true });

  for (const artwork of ARTWORKS) {
    const svg = artwork.render();
    await writeFile(path.join(CANONICAL_DIR, artwork.file), svg, "utf8");
    await writeFile(path.join(RUNTIME_DIR, artwork.file), svg, "utf8");
  }

  console.log(`[art] ${ARTWORKS.length} project artwork(s) written.`);
}

main().catch((error) => {
  console.error("[art] generation failed:", error);
  process.exit(1);
});
