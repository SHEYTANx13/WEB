/* 2 — UHIT: the intelligence measurement programme                     */
/* A rising benchmark scale: evaluation bars, a dashed elite            */
/* threshold, one ringed result.                                        */
/* ------------------------------------------------------------------ */

function uhitArtwork() {
  const parts = [dotGrid()];
  const baseY = 500;
  const bars = [
    { x: 150, h: 130 },
    { x: 260, h: 185 },
    { x: 370, h: 240 },
    { x: 480, h: 215 },
    { x: 590, h: 300, highlight: true },
    { x: 700, h: 345 },
    { x: 810, h: 320 },
    { x: 920, h: 390 },
    { x: 1030, h: 430 }
  ];
  const barWidth = 26;

  /* Baseline */
  parts.push(link(100, baseY, 1100, baseY, { stroke: C.inkDim, width: 1.6 }));

  for (const bar of bars) {
    const y = baseY - bar.h;
    const fill = bar.highlight ? C.red : C.line;
    const stroke = bar.highlight ? C.red : C.inkDim;
    parts.push(
      `<rect x="${bar.x - barWidth / 2}" y="${y}" width="${barWidth}" height="${bar.h}" fill="${fill}" stroke="${stroke}" stroke-width="1.2"/>`
    );
    if (bar.highlight) {
      parts.push(node(bar.x, y, { r: 6, fill: C.red, ring: C.redDim }));
    }
  }

  /* Elite threshold */
  parts.push(link(100, 96, 1100, 96, { stroke: C.red, width: 1.4, dash: "10 8" }));
  parts.push(
    `<circle cx="1100" cy="96" r="3" fill="${C.red}"/>`
  );

  /* Stepped result curve connecting the bar tops */
  const steps = bars
    .map((bar) => `${bar.x},${baseY - bar.h}`)
    .join(" L");
  parts.push(
    `<path d="M${steps}" fill="none" stroke="${C.ink}" stroke-width="1.6" opacity="0.85"/>`
  );

  return wrap(
    "UHIT intelligence measurement — a rising scale of evaluation bars under a dashed elite threshold, one result ringed and marked in red",
    parts.join("\n  ")
  );
}

