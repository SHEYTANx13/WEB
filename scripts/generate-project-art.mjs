#!/usr/bin/env node
/*
 * generate-project-art.mjs — featured-project artwork generator (v2.9).
 *
 * Produces the five featured-project images used by the home scene's
 * "What I have actually built" cards. These are ORIGINAL abstract
 * system diagrams — they represent what each project IS (an agent
 * loop, a benchmark scale, a proxy mesh, an organism, a route tree),
 * drawn in the site's brand vocabulary. No fake screenshots, no
 * invented UI, no stock imagery.
 *
 * Deterministic: same script, same bytes. Outputs are committed in
 * two places:
 *   assets/illustrations/        — canonical source of truth
 *   public/images/projects/      — runtime copies the site serves
 *
 * Geometry-only compositions (no <text>): the images carry meaning
 * through structure, their alt text carries the explanation, and no
 * font ever has to resolve for them to be faithful.
 *
 * Zero dependencies. Run: node scripts/generate-project-art.mjs
 */

import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const SCRIPT_DIR = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(SCRIPT_DIR, "..");

const CANONICAL_DIR = path.join(ROOT, "assets", "illustrations");
const RUNTIME_DIR = path.join(ROOT, "public", "images", "projects");

const SVG_NS = 'xmlns="http://www.w3.org/2000/svg"';

/* Palette — the site's own tokens, so artwork and UI never clash. */
const C = {
  bg: "#0a0a0c",
  panel: "#0d0d10",
  line: "#23262d",
  lineSoft: "#191b20",
  ink: "#c9cdd4",
  inkDim: "#565b64",
  red: "#ff2020",
  redDeep: "#a90000",
  redDim: "rgba(255, 32, 32, 0.34)"
};

const ART_HEADER = `<!--
  Parsa Tak — featured-project artwork. Original abstract system
  diagram (no screenshots, no invented UI). Generated by
  scripts/generate-project-art.mjs — regenerate, never hand-edit.
-->`;

/* ------------------------------------------------------------------ */
/* Small composition helpers                                            */
/* ------------------------------------------------------------------ */

/** Faint engineering dot-grid backdrop shared by every artwork.
 * One <pattern> + one rect — tiny bytes, identical look. */
function dotGrid() {
  return `<defs>
    <pattern id="dotgrid" width="40" height="40" patternUnits="userSpaceOnUse">
      <circle cx="40" cy="45" r="1" fill="${C.lineSoft}"/>
    </pattern>
  </defs>
  <rect width="1200" height="630" fill="url(#dotgrid)" opacity="0.5"/>`;
}

/** Circle node, optionally ringed/highlighted. */
function node(cx, cy, { r = 7, fill = C.inkDim, ring = null } = {}) {
  const ringMarkup = ring
    ? `<circle cx="${cx}" cy="${cy}" r="${r + 7}" fill="none" stroke="${ring}" stroke-width="1.4" opacity="0.8"/>`
    : "";
  return `${ringMarkup}<circle cx="${cx}" cy="${cy}" r="${r}" fill="${fill}"/>`;
}

/** Straight connector line. */
function link(x1, y1, x2, y2, { stroke = C.line, width = 1.4, opacity = 1, dash = null } = {}) {
  const dashAttr = dash ? ` stroke-dasharray="${dash}"` : "";
  return `<line x1="${x1}" y1="${y1}" x2="${x2}" y2="${y2}" stroke="${stroke}" stroke-width="${width}" opacity="${opacity}"${dashAttr}/>`;
}

/** Rounded-corner frame. */
function frame(x, y, w, h, { stroke = C.line, width = 1.6, fill = "none", rx = 14, dash = null } = {}) {
  const dashAttr = dash ? ` stroke-dasharray="${dash}"` : "";
  return `<rect x="${x}" y="${y}" width="${w}" height="${h}" rx="${rx}" fill="${fill}" stroke="${stroke}" stroke-width="${width}"${dashAttr}/>`;
}

/** Arrow head at (x, y) pointing along (dx, dy). */
function arrowHead(x, y, dx, dy, { stroke = C.red, size = 7 } = {}) {
  const len = Math.hypot(dx, dy);
  const ux = dx / len;
  const uy = dy / len;
  const px = -uy;
  const py = ux;
  const ax = x - ux * size;
  const ay = y - uy * size;
  const p1 = `${ax + px * size * 0.6},${ay + py * size * 0.6}`;
  const p2 = `${ax - px * size * 0.6},${ay - py * size * 0.6}`;
  return `<path d="M${p1} L${x},${y} L${p2}" fill="none" stroke="${stroke}" stroke-width="1.6" stroke-linecap="round" stroke-linejoin="round"/>`;
}

/** The 13-point brand star as a small interior echo. Reuses the exact
 * {13/5} polar construction from generate-brand.mjs. */
function brandStar(cx, cy, outerRadius, fill) {
  const innerRatio =
    Math.cos((5 * Math.PI) / 13) / Math.cos((4 * Math.PI) / 13);
  const innerRadius = outerRadius * innerRatio;
  const points = [];
  for (let i = 0; i < 26; i += 1) {
    const angle = (-90 + i * (360 / 26)) * (Math.PI / 180);
    const radius = i % 2 === 0 ? outerRadius : innerRadius;
    points.push(`${(cx + radius * Math.cos(angle)).toFixed(3)},${(cy + radius * Math.sin(angle)).toFixed(3)}`);
  }
  return `<polygon points="${points.join(" ")}" fill="${fill}"/>`;
}

function wrap(title, body) {
  return `<?xml version="1.0" encoding="UTF-8"?>
<svg ${SVG_NS} viewBox="0 0 1200 630" role="img" aria-labelledby="artTitle">
  <title id="artTitle">${title}</title>
  ${ART_HEADER.replace(/\n/g, `\n  `)}
  <rect width="1200" height="630" fill="${C.bg}"/>
  ${body.trim()}
</svg>
`;
}

/* ------------------------------------------------------------------ */
/* 1 — SHEYTAN: the local agent laboratory                              */
/* A framed local workspace containing a four-stage agent loop          */
/* (plan → act → verify → remember) around a red 13-point core.         */
/* ------------------------------------------------------------------ */

function sheytanArtwork() {
  const cx = 600;
  const cy = 315;
  const stages = [
    { x: cx, y: cy - 150, label: "plan", fill: C.ink },
    { x: cx + 150, y: cy, label: "act", fill: C.ink },
    { x: cx, y: cy + 150, label: "verify", fill: C.red, ring: C.redDim },
    { x: cx - 150, y: cy, label: "remember", fill: C.ink }
  ];

  const parts = [dotGrid()];
  parts.push(frame(cx - 268, cy - 208, 536, 416, { rx: 18 }));
  parts.push(frame(cx - 246, cy - 186, 492, 372, { stroke: C.lineSoft, width: 1, rx: 12 }));

  /* Loop edges with directional arrows (clockwise). */
  const edges = [
    [stages[0], stages[1]],
    [stages[1], stages[2]],
    [stages[2], stages[3]],
    [stages[3], stages[0]]
  ];
  for (const [a, b] of edges) {
    const dx = b.x - a.x;
    const dy = b.y - a.y;
    const trimA = 26;
    const trimB = 30;
    const len = Math.hypot(dx, dy);
    const sx = a.x + (dx / len) * trimA;
    const sy = a.y + (dy / len) * trimA;
    const ex = b.x - (dx / len) * trimB;
    const ey = b.y - (dy / len) * trimB;
    parts.push(
      `<path d="M${sx},${sy} L${ex},${ey}" stroke="${C.line}" stroke-width="1.6"/>`
    );
    parts.push(arrowHead(ex, ey, dx, dy));
  }

  for (const stage of stages) {
    parts.push(node(stage.x, stage.y, { r: 8, fill: stage.fill, ring: stage.ring }));
  }

  parts.push(brandStar(cx, cy, 34, C.red));
  parts.push(
    `<circle cx="${cx}" cy="${cy}" r="62" fill="none" stroke="${C.line}" stroke-width="1" stroke-dasharray="3 6"/>`
  );

  /* Local-workspace corner ticks (the "desktop" tell). */
  const tick = 22;
  const corners = [
    [cx - 268, cy - 208, 1, 1],
    [cx + 268, cy - 208, -1, 1],
    [cx - 268, cy + 208, 1, -1],
    [cx + 268, cy + 208, -1, -1]
  ];
  for (const [x, y, sx2, sy2] of corners) {
    parts.push(
      `<path d="M${x + sx2 * tick},${y} L${x},${y} L${x},${y + sy2 * tick}" fill="none" stroke="${C.inkDim}" stroke-width="2"/>`
    );
  }

  return wrap(
    "SHEYTAN local agent laboratory — four-stage agent loop around a red 13-point core inside a framed local workspace",
    parts.join("\n  ")
  );
}

