/* 3 — FreeIran: the proxy mesh with routing tunnels                    */
/* A field of proxy nodes; two bright tunnels cross it toward a         */
/* ringed client node.                                                  */
/* ------------------------------------------------------------------ */

function freeiranArtwork() {
  const parts = [dotGrid()];

  const meshNodes = [
    [140, 120], [320, 90], [520, 140], [760, 100], [980, 150], [1090, 260],
    [180, 320], [400, 300], [640, 330], [880, 300], [1030, 420],
    [150, 520], [350, 540], [600, 500], [820, 540], [990, 500]
  ];

  /* Faint mesh edges */
  const edges = [
    [0, 1], [1, 2], [2, 3], [3, 4], [4, 5],
    [0, 6], [1, 7], [2, 8], [3, 9], [4, 10],
    [6, 7], [7, 8], [8, 9], [9, 10],
    [6, 11], [7, 12], [8, 13], [9, 14], [10, 15],
    [11, 12], [12, 13], [13, 14], [14, 15]
  ];
  for (const [a, b] of edges) {
    parts.push(link(meshNodes[a][0], meshNodes[a][1], meshNodes[b][0], meshNodes[b][1], { opacity: 0.55 }));
  }

  for (const [x, y] of meshNodes) {
    parts.push(node(x, y, { r: 5.5 }));
  }

  /* Tunnel one: client → north-east */
  const tunnelOne = `M150,520 C360,420 420,220 760,100`;
  parts.push(
    `<path d="${tunnelOne}" fill="none" stroke="${C.red}" stroke-width="2.4" stroke-linecap="round"/>`
  );
  parts.push(arrowHead(760, 100, 400, -360));

  /* Tunnel two: client → east */
  const tunnelTwo = `M150,520 C420,470 660,430 1030,420`;
  parts.push(
    `<path d="${tunnelTwo}" fill="none" stroke="${C.red}" stroke-width="2.4" stroke-linecap="round" opacity="0.75"/>`
  );
  parts.push(arrowHead(1030, 420, 360, -40));

  /* The client (tested, maintained, running) */
  parts.push(node(150, 520, { r: 8, fill: C.red, ring: C.redDim }));
  parts.push(
    `<circle cx="150" cy="520" r="26" fill="none" stroke="${C.line}" stroke-width="1" stroke-dasharray="3 5"/>`
  );

  return wrap(
    "FreeIran proxy mesh — a field of network nodes with two bright routing tunnels crossing it toward a highlighted client node",
    parts.join("\n  ")
  );
}

