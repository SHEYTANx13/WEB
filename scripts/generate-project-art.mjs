/* 4 — RED MAGIC: the computational organism                            */
/* A red nucleus inside breathing membranes with signal particles.      */
/* ------------------------------------------------------------------ */

function redMagicArtwork() {
  const parts = [];
  const cx = 600;
  const cy = 315;

  /* Red vignette halo */
  parts.push(
    `<radialGradient id="halo" cx="50%" cy="50%" r="50%">
      <stop offset="0%" stop-color="rgba(255,32,32,0.5)"/>
      <stop offset="55%" stop-color="rgba(255,32,32,0.14)"/>
      <stop offset="100%" stop-color="rgba(255,0,0,0)"/>
    </radialGradient>`
  );
  parts.push(`<circle cx="${cx}" cy="${cy}" r="300" fill="url(#halo)"/>`);

  /* Breathing membranes */
  const membranes = [196, 148, 104];
  membranes.forEach((r, index) => {
    parts.push(
      `<circle cx="${cx}" cy="${cy}" r="${r}" fill="none" stroke="${C.red}" stroke-width="${1.8 - index * 0.3}" opacity="${0.85 - index * 0.22}"/>`
    );
  });

  /* Core */
  parts.push(`<circle cx="${cx}" cy="${cy}" r="54" fill="${C.redDeep}"/>`);
  parts.push(`<circle cx="${cx}" cy="${cy}" r="54" fill="none" stroke="${C.red}" stroke-width="1.6"/>`);
  parts.push(`<circle cx="${cx}" cy="${cy}" r="26" fill="${C.red}"/>`);
  parts.push(`<circle cx="${cx - 12}" cy="${cy - 14}" r="7" fill="rgba(255,244,239,0.85)"/>`);

  /* Flow currents between core and membrane */
  for (let i = 0; i < 6; i += 1) {
    const angle = (i * 60 + 18) * (Math.PI / 180);
    const x1 = cx + 62 * Math.cos(angle);
    const y1 = cy + 62 * Math.sin(angle);
    const x2 = cx + 140 * Math.cos(angle);
    const y2 = cy + 140 * Math.sin(angle);
    parts.push(
      `<path d="M${x1.toFixed(1)},${y1.toFixed(1)} Q${(cx + 100 * Math.cos(angle + 0.22)).toFixed(1)},${(cy + 100 * Math.sin(angle + 0.22)).toFixed(1)} ${x2.toFixed(1)},${y2.toFixed(1)}" fill="none" stroke="${C.red}" stroke-width="1.2" opacity="0.6"/>`
    );
  }

  /* Signal particles */
  const particles = [
    [330, 180, 3.2], [420, 120, 2.2], [790, 140, 2.8], [880, 230, 2.1],
    [860, 430, 3.4], [700, 500, 2.3], [420, 480, 2.9], [300, 400, 2.0],
    [950, 330, 2.4], [520, 210, 1.9]
  ];
  for (const [x, y, r] of particles) {
    parts.push(`<circle cx="${x}" cy="${y}" r="${r}" fill="${C.red}" opacity="0.85"/>`);
  }

  return wrap(
    "RED MAGIC computational organism — a red nucleus inside three breathing membranes with flow currents and orbiting signal particles",
    parts.join("\n  ")
  );
}

